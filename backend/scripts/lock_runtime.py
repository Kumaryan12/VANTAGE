"""Derive the implemented production dependency closure from installed locked distributions."""

import importlib.metadata
import tomllib
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[2]


def main():
    project = tomllib.loads((ROOT / "backend/pyproject.toml").read_text())["project"]
    queue = [Requirement(value) for value in project["dependencies"]]
    selected = {}
    extras = {}
    environment = {
        **default_environment(),
        "sys_platform": "linux",
        "platform_system": "Linux",
        "os_name": "posix",
    }
    while queue:
        requirement = queue.pop()
        name = canonicalize_name(requirement.name)
        requested = set(requirement.extras)
        if name in selected and requested.issubset(extras[name]):
            continue
        distribution = importlib.metadata.distribution(name)
        selected[name] = distribution.version
        extras[name] = extras.get(name, set()) | requested
        for raw in distribution.requires or []:
            child = Requirement(raw)
            if child.marker is None or any(
                child.marker.evaluate({**environment, "extra": extra})
                for extra in {"", *extras[name]}
            ):
                queue.append(child)
    output = (
        "# Generated by backend/scripts/lock_runtime.py from the full locked environment.\n"
        + "".join(f"{name}=={version}\n" for name, version in sorted(selected.items()))
    )
    (ROOT / "backend/requirements.runtime.lock").write_text(output)
    print(f"Locked {len(selected)} runtime distributions; test/lint dependencies are excluded.")


if __name__ == "__main__":
    main()
